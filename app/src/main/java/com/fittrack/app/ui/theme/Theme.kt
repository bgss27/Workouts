/**
 * Softer, larger radii than the Material defaults. Cards pick up `medium`,
 * sheets and dialogs `extraLarge`, chips `small`.
 */
val FitTrackShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(20.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(32.dp),
)

/**
 * @param dynamicColor When true on Android 12+, the wallpaper-derived palette
 * replaces the brand scheme. Off by default so FitTrack keeps its own look;
 * Settings can flip it on for users who prefer Material You.
 */
@Composable
fun FitTrackTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val semanticColors = if (darkTheme) DarkFitTrackColors else LightFitTrackColors

    CompositionLocalProvider(LocalFitTrackColors provides semanticColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = FitTrackShapes,
            content = content
        )
    }
}
